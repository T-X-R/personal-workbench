function formatToday(date: string, locale: string) {
  return new Intl.DateTimeFormat(locale, { dateStyle: 'full' }).format(new Date(`${date}T12:00:00`))
}

function workspaceName(cwd: string) {
  const parts = cwd.split('/').filter(Boolean)
  return parts.at(-1) || cwd || '—'
}

function CodexDailyReviewPage({ host }: CapabilityPageProps) {
  const environment = useSyncExternalStore(host.environment.subscribe, host.environment.getSnapshot, host.environment.getSnapshot)
  const review = useSyncExternalStore(codexDailyReviewStore.subscribe, codexDailyReviewStore.getSnapshot, codexDailyReviewStore.getSnapshot)
  const copy = messages[environment.language]
  const { date, phase, source, summary, error } = review

  useEffect(() => {
    void codexDailyReviewStore.restore(host)
  }, [host])

  const stats = useMemo(() => {
    const sessions = source?.sessions ?? []
    return {
      sessions: sessions.length,
      turns: sessions.reduce((total, session) => total + session.turns.length, 0),
      workspaces: new Set(sessions.map((session) => session.cwd).filter(Boolean)).size,
    }
  }, [source])

  const busy = phase === 'scanning' || phase === 'summarizing'
  const statusText = phase === 'scanning' ? copy.scanning
    : phase === 'summarizing' ? copy.summarizing
      : phase === 'ready' ? copy.ready
        : phase === 'empty' ? copy.empty
          : phase === 'error' ? copy.error
            : copy.waiting

  return (
    <div className="codex-review-page" lang={environment.locale} data-theme={environment.theme}>
      <header className="codex-review-header">
        <div>
          <span className="codex-review-eyebrow">{copy.eyebrow}</span>
          <h1>{copy.title}</h1>
          <p>{copy.subtitle}</p>
        </div>
        <button className="codex-review-refresh" onClick={() => void codexDailyReviewStore.runReview(host, environment.language)} disabled={busy}>
          <ReloadIcon className={busy ? 'codex-review-spin' : ''} />
          {phase === 'idle' ? copy.run : copy.refresh}
        </button>
      </header>

      <div className="codex-review-date"><ClockIcon />{formatToday(date, environment.locale)}</div>

      <section className={`codex-review-status codex-review-status-${phase}`} aria-live="polite">
        <span className="codex-review-status-icon">
          {phase === 'error' ? <ExclamationTriangleIcon /> : phase === 'ready' ? <CheckCircledIcon /> : <ReloadIcon className={busy ? 'codex-review-spin' : ''} />}
        </span>
        <div><strong>{statusText}</strong>{phase === 'error' && <small>{error}<br />{copy.retryHint}</small>}</div>
      </section>

      <div className="codex-review-stats">
        <div><span>{copy.sessions}</span><strong>{stats.sessions}</strong></div>
        <div><span>{copy.turns}</span><strong>{stats.turns}</strong></div>
        <div><span>{copy.workspaces}</span><strong>{stats.workspaces}</strong></div>
      </div>

      <div className="codex-review-layout">
        <section className="codex-review-summary">
          <div className="codex-review-section-heading">
            <div><span>DAILY REVIEW</span><h2>{copy.reviewTitle}</h2></div>
            {summary && <small>{copy.generatedBy} {summary.provider} · {summary.model}</small>}
          </div>
          {summary
            ? <div className="codex-review-output"><Markdown remarkPlugins={[remarkGfm]}>{summary.output}</Markdown></div>
            : <div className="codex-review-placeholder"><FileTextIcon /><span>{statusText}</span></div>}
        </section>

        <aside className="codex-review-sources">
          <div className="codex-review-section-heading"><div><span>SESSION SOURCES</span><h2>{copy.sourceTitle}</h2></div><small>{source?.scannedFileCount ?? 0}</small></div>
          <p>{copy.sourceHint}</p>
          <div className="codex-review-source-list">
            {source?.sessions.map((session) => <div className="codex-review-source" key={session.id}>
              <span><strong>{workspaceName(session.cwd)}</strong><small>{session.turns.length} {copy.turns}</small></span>
              <em>{session.archived ? copy.archived : copy.active}</em>
            </div>)}
          </div>
        </aside>
      </div>

    </div>
  )
}

const codexDailyReviewCapability: CapabilityModule = {
  manifest,
  Page: (props: CapabilityPageProps) => <CodexDailyReviewPage {...props} />,
}

export default codexDailyReviewCapability

export { CodexDailyReviewPage, manifest }
